    assert facts["BUILD_GIT_SHA"] == _git(repo, "rev-parse", "HEAD", env=clean_env)
    assert facts["BUILD_GIT_SHA"] != STALE["GIT_SHA"]
    assert facts["BUILD_VERSION"] == "3.0.2"
    assert facts["BUILD_DIRTY"] == "false"


