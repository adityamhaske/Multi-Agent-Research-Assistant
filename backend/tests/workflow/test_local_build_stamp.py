"""
A local image reports its own build identity, or `unknown` — never another build's.

`research_engine/_build.py` is git-ignored but deliberately not Docker-ignored: `release.yml`
writes a fresh stamp into the build context, and `COPY . /app` is how the published images
carry it. The same COPY carried a developer's leftover stamp into every image `./start.sh`
built — a local build of 3.0.2 answered `/api/v1/version` with 2.1.0 and a September commit
(release-audit/v3.0.2, Finding 7).

So an image build does not trust its context unless it says so. The backend Dockerfile's
default, `BUILD_STAMP=local`, discards whatever stamp the context carries and writes a fresh
one only from the facts `start.sh` read from git for this build; only `release.yml`, whose
own job wrote the stamp, passes `BUILD_STAMP=context` to keep it. Every test that exercises
the local path plants the stale stamp first: in a clean checkout there is no stamp to leak,
and the bug passes.

The desktop bundle is the same leak through a different door: `research-sidecar.spec` bundles
whatever `_build.py` the checkout holds. `desktop.yml` stamps a fresh checkout right before
PyInstaller and then asks the frozen engine for its commit, so CI cannot ship a stale stamp —
but a hand-run build can, so the spec refuses a stamp `stamp_build.py --check` rejects.

And a source checkout is a third door: `make backend-dev`, the CLI and a source-run sidecar
read the same leftover file. There the checkout itself can contradict the stamp, so
`build_info()` reports `unknown` when it does. The tree only ever vetoes a stamp; it never
supplies an answer — that would be the guess `build_info.py` exists to refuse.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[3]
BACKEND = ROOT / "backend"
STEP = "docker/stamp_image.py"
#: The one set of names every layer uses: start.sh exports them, compose forwards them as
#: build args, the Dockerfile declares them, the stamping step reads them.
FACTS = ("BUILD_VERSION", "BUILD_GIT_SHA", "BUILD_DIRTY")

STALE = {
    "VERSION": "2.1.0",
    "GIT_SHA": "33f1916" + "0" * 33,
    "DIRTY": False,
    "CONTRACT_VERSION": "5ca1ab1e5ca1ab1e",
    "BUILT_AT": "2026-09-27T12:00:00+00:00",
}
HEAD = "c0ffee" + "1" * 34


def _stamp_source(values: dict) -> str:
    """The format `scripts/stamp_build.py` writes."""
    lines = ['"""Generated by scripts/stamp_build.py. Not checked in; see build_info.py."""', ""]
    lines += [f"{key} = {value!r}" for key, value in values.items()]
    return "\n".join(lines) + "\n"


def _image_tree(tmp_path: Path, planted: dict = STALE) -> Path:
    """The image's `/app` layout, reduced to what the stamping step and the reader touch.

    The real step and the real reader, copied — not imported — so the checkout's own
    `_build.py` (or its absence) cannot answer in place of the planted one.
    """
    (tmp_path / "docker").mkdir()
    shutil.copy(BACKEND / STEP, tmp_path / STEP)
    package = tmp_path / "research_engine"
    package.mkdir()
    (package / "__init__.py").write_text("")
    shutil.copy(BACKEND / "research_engine" / "build_info.py", package / "build_info.py")
    (package / "_build.py").write_text(_stamp_source(planted))
    return tmp_path


def _build_step(tree: Path, **facts: str) -> subprocess.CompletedProcess[str]:
    """Run the step exactly as the Dockerfile does: `python docker/stamp_image.py` in /app."""
    env = {k: v for k, v in os.environ.items() if not k.startswith("BUILD_")}
    env.update(facts)
    return subprocess.run(
        [sys.executable, STEP], cwd=tree, env=env, capture_output=True, text=True, check=False
    )


def _reported(tree: Path) -> dict:
    """What `/api/v1/version` would serve from this tree.

    An editable install of `research_engine` could answer from a different checkout; the
    assertion on `__file__` proves the tree's own copy did.
    """
    probe = (
        "import json, research_engine; from research_engine.build_info import build_info;"
        "print(json.dumps({'file': research_engine.__file__, **build_info().as_dict()}))"
    )
    out = subprocess.run(
        [sys.executable, "-B", "-c", probe],
        cwd=tree,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    reported = json.loads(out)
    assert Path(reported.pop("file")).resolve().is_relative_to(tree.resolve())
    return reported


# ── The stamping step ─────────────────────────────────────────────────────────────


def test_a_local_build_without_an_identity_reports_unknown_not_the_stale_stamp(tmp_path):
    """Plain `docker compose up --build` — no start.sh, so nobody read git. Honest absence."""
    tree = _image_tree(tmp_path)
    result = _build_step(tree, BUILD_STAMP="local")

    assert result.returncode == 0, result.stderr
    reported = _reported(tree)
    assert reported["version"] == "unknown"
    assert reported["git_sha"] == "unknown"
    assert reported["built_at"] == "unknown"


@pytest.mark.parametrize("dirty", ["true", "false"])
def test_a_local_build_reports_the_identity_it_was_built_from(tmp_path, dirty):
    tree = _image_tree(tmp_path)
    result = _build_step(
        tree, BUILD_STAMP="local", BUILD_VERSION="3.0.2", BUILD_GIT_SHA=HEAD, BUILD_DIRTY=dirty
    )

    assert result.returncode == 0, result.stderr
    reported = _reported(tree)
    assert reported["version"] == "3.0.2"
    assert reported["git_sha"] == HEAD
    assert reported["dirty"] is (dirty == "true")
    assert reported["built_at"] not in ("unknown", STALE["BUILT_AT"])
    # Not hashed on a local build, and above all not inherited from the stale stamp.
    assert reported["contract_version"] == "unknown"


@pytest.mark.parametrize(
    "facts",
    [
        pytest.param({"BUILD_GIT_SHA": HEAD, "BUILD_DIRTY": "false"}, id="no-version"),
        pytest.param({"BUILD_VERSION": "3.0.2", "BUILD_DIRTY": "false"}, id="no-commit"),
        pytest.param({"BUILD_VERSION": "3.0.2", "BUILD_GIT_SHA": HEAD}, id="no-dirty"),
        pytest.param(
            {"BUILD_VERSION": "3.0.2", "BUILD_GIT_SHA": "33f1916", "BUILD_DIRTY": "false"},
            id="abbreviated-commit",
        ),
        pytest.param(
            {"BUILD_VERSION": "3.0.2", "BUILD_GIT_SHA": HEAD, "BUILD_DIRTY": "yes"},
            id="dirty-not-a-boolean",
        ),
        pytest.param(
            {"BUILD_VERSION": "3.0.2'\nGIT_SHA = 'x", "BUILD_GIT_SHA": HEAD, "BUILD_DIRTY": "0"},
            id="version-that-is-code",
        ),
    ],
)
def test_an_incomplete_identity_is_unknown_rather_than_partly_true(tmp_path, facts):
    """A stamp is a claim about the whole build: half a stamp would be read as a whole one."""
    tree = _image_tree(tmp_path)
    result = _build_step(tree, BUILD_STAMP="local", **facts)

    assert result.returncode == 0, result.stderr
    reported = _reported(tree)
    assert reported["version"] == "unknown"
    assert reported["git_sha"] == "unknown"


def test_a_release_build_keeps_the_stamp_it_was_handed(tmp_path):
    """`release.yml` stamps the context fresh and asks the image to keep it; dropping it would
    leave every published image answering `unknown`."""
    fresh = {**STALE, "VERSION": "3.0.2", "GIT_SHA": HEAD, "BUILT_AT": "2026-10-18T00:00:00+00:00"}
    tree = _image_tree(tmp_path, planted=fresh)
    result = _build_step(tree, BUILD_STAMP=_release_build_args()["BUILD_STAMP"])

    assert result.returncode == 0, result.stderr
    reported = _reported(tree)
    assert reported["git_sha"] == HEAD
    assert reported["contract_version"] == fresh["CONTRACT_VERSION"]


def test_the_step_with_no_mode_trusts_no_stamp(tmp_path):
    """Keeping a context's stamp is something a build must ask for, never what it gets."""
    tree = _image_tree(tmp_path)
    result = _build_step(tree)

    assert result.returncode == 0, result.stderr
    assert _reported(tree)["git_sha"] == "unknown"


def test_an_unrecognised_mode_fails_the_build(tmp_path):
    """A typo in compose must not quietly fall back to keeping whatever the context had."""
    tree = _image_tree(tmp_path)
    result = _build_step(tree, BUILD_STAMP="locla")

    assert result.returncode != 0
    assert "locla" in result.stderr


# ── The wiring: compose → Dockerfile → step ───────────────────────────────────────


def _dockerfile_runtime_stage() -> list[str]:
    lines = [ln.strip() for ln in (BACKEND / "Dockerfile").read_text().splitlines()]
    start = lines.index("FROM base AS runtime")
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith("FROM "))
    return lines[start:end]


def _dockerfile_default(arg: str) -> str:
    for line in _dockerfile_runtime_stage():
        if match := re.fullmatch(rf"ARG {arg}=(\S*)", line):
            return match.group(1)
    raise AssertionError(f"the runtime stage declares no default for {arg}")


def test_the_dockerfile_restamps_after_copying_the_context():
    """Before the COPY there is nothing to discard; the step has to see what COPY brought."""
    stage = _dockerfile_runtime_stage()
    copy = stage.index("COPY --chown=appuser:appuser . /app")
    run = stage.index(f"RUN python {STEP}")
    assert copy < run
    declared = [ln.split()[1].split("=")[0] for ln in stage[:run] if ln.startswith("ARG ")]
    assert set(FACTS) | {"BUILD_STAMP"} <= set(declared)


def test_every_compose_built_backend_image_is_stamped_as_local():
    """Every service built from ./backend, so a third one added later is covered too."""
    services = yaml.safe_load((ROOT / "docker-compose.full.yml").read_text())["services"]
    backend = {
        name: svc["build"]
        for name, svc in services.items()
        if isinstance(svc.get("build"), dict) and svc["build"].get("context") == "./backend"
    }
    assert set(backend) >= {"api", "worker"}
    for name, build in backend.items():
        args = build.get("args") or {}
        assert args.get("BUILD_STAMP") == "local", name
        for fact in FACTS:
            assert args.get(fact) == f"${{{fact}:-}}", f"{name}: {fact}"


def _release_build_args() -> dict[str, str]:
    """The build args `release.yml` hands the image build, as `KEY=value` lines."""
    workflow = yaml.safe_load((ROOT / ".github" / "workflows" / "release.yml").read_text())
    steps = [
        step
        for step in workflow["jobs"]["build"]["steps"]
        if str(step.get("uses", "")).startswith("docker/build-push-action@")
    ]
    assert len(steps) == 1, "expected one image build step in release.yml"
    lines = str(steps[0].get("with", {}).get("build-args", "")).splitlines()
    return dict(line.strip().split("=", 1) for line in lines if line.strip())


def test_a_hand_run_image_build_trusts_no_stamp():
    """`docker build backend` with no arguments: the context's stamp is whatever the checkout
    happened to hold, so the default is to drop it and answer `unknown`."""
    assert _dockerfile_default("BUILD_STAMP") == "local"


def test_the_release_workflow_keeps_the_stamp_it_made():
    """The one build allowed to trust the context, because its `stamp` job just wrote it.
    Without the opt-in the published images drop it; the image check would catch that only
    on a tag, after the build."""
    assert _release_build_args().get("BUILD_STAMP") == "context"


# ── start.sh: the only place that reads git ───────────────────────────────────────

FAKE_DOCKER = """#!/usr/bin/env bash
# Records the build facts compose would interpolate, and answers just enough of the
# docker CLI for start.sh to run to completion.
case " $* " in
  *" up "*) env | grep '^BUILD_' > "$FAKE_DOCKER_LOG" || true ;;
  *" ps -q "*) echo fake-container ;;
  *" inspect "*) case "$*" in *Health*) echo healthy ;; *) echo true ;; esac ;;
esac
exit 0
"""


def _git(repo: Path, *args: str, env: dict) -> str:
    return subprocess.run(
        ["git", *args], cwd=repo, env=env, capture_output=True, text=True, check=True
    ).stdout.strip()


def _checkout(tmp_path: Path, env: dict, *, git: bool) -> Path:
    repo = tmp_path / "checkout"
    stamp = repo / "backend" / "research_engine" / "_build.py"
    stamp.parent.mkdir(parents=True)
    shutil.copy(ROOT / "start.sh", repo / "start.sh")
    (repo / "VERSION").write_text("3.0.2\n")
    (repo / ".env").write_text(f"JWT_SECRET_KEY={'k' * 64}\nGOOGLE_API_KEY=placeholder\n")
    (repo / ".gitignore").write_text(".env\nbackend/research_engine/_build.py\n")
    if git:
        _git(repo, "init", "-q", env=env)
        _git(repo, "add", "-A", env=env)
        _git(repo, "commit", "-q", "-m", "fixture", env=env)
    # Planted after the commit, git-ignored, exactly as a leftover sits in a real checkout.
    stamp.write_text(_stamp_source(STALE))
    return repo


def _start(repo: Path, tmp_path: Path, env: dict) -> dict:
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir(exist_ok=True)
    stubs = {"docker": FAKE_DOCKER, "lsof": "#!/bin/sh\nexit 1\n"}
    stubs |= {"open": "#!/bin/sh\nexit 0\n", "xdg-open": "#!/bin/sh\nexit 0\n"}
    for name, body in stubs.items():
        (bin_dir / name).write_text(body)
        (bin_dir / name).chmod(0o755)
    log = tmp_path / "docker-env.log"
    run_env = {**env, "PATH": f"{bin_dir}{os.pathsep}{env['PATH']}", "FAKE_DOCKER_LOG": str(log)}
    result = subprocess.run(
        ["bash", "start.sh"], cwd=repo, env=run_env, capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, result.stdout + result.stderr
    pairs = (line.split("=", 1) for line in log.read_text().splitlines())
    return dict(pairs)


