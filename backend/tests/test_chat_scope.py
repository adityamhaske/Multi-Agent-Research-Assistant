# ── Web scope: new sources, and they come back ─────────────────────────────────────


@pytest.mark.asyncio
async def test_web_scope_returns_the_sources_it_found(monkeypatch):
    """A web-scoped answer cites pages the report never had, so those sources have to
    reach the client — otherwise its `[n]` markers resolve to nothing, which is the one
    thing this product refuses to ship."""

    async def fake_search(query: str, max_results: int = 5):
        return [
            {"url": "https://arxiv.org/abs/1", "title": "Recent work", "content": "A finding."},
        ]

    monkeypatch.setattr("research_engine.retrievers.search", fake_search)

    grounding = await chat_scope.gather(
        "web",
        query="2026 results",
        report=None,
        report_sources=[],
        memory_excerpts=None,
        store_factory=lambda: None,
    )

    assert [s["url"] for s in grounding.sources] == ["https://arxiv.org/abs/1"]
    assert "Recent work" in grounding.text
    # Numbered from 1 so the model's [n] markers resolve against this list.
    assert grounding.sources[0]["index"] == 1


@pytest.mark.asyncio
async def test_a_failed_web_search_is_reported_not_swallowed(monkeypatch):
    """AGENTS.md, "never fake, never swallow": an unavailable retriever must reach the
    answer as a stated gap, not as an empty grounding block the model papers over."""

    async def boom(query: str, max_results: int = 5):
        raise RuntimeError("every retriever failed: tavily 429, brave 401")

    monkeypatch.setattr("research_engine.retrievers.search", boom)

    grounding = await chat_scope.gather(
        "web",
        query="anything",
        report=None,
        report_sources=[],
        memory_excerpts=None,
        store_factory=lambda: None,
    )

    assert grounding.sources == []
    assert any("429" in n or "retriever" in n.lower() for n in grounding.notes)


