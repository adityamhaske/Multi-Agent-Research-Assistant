# ── A store that behaves like CorpusStore without needing a file ───────────────────


class _FakeStore:
    """Exercises the *real* guard: `search` runs the same `is_local` check `CorpusStore`
    does, so a test that passes here would pass against the real store for the same
    reason. Only the SQLite file is absent."""

    def __init__(self, embedder: _Embedder) -> None:
        self._embedder = embedder

    async def search(self, query: str, max_results: int) -> list[dict]:
        if not getattr(self._embedder, "is_local", False):
            raise EmbeddingsUnavailable(
                f"Corpus scope reads only your uploaded documents, but the configured "
                f"embeddings provider '{self._embedder.model_id}' is remote — every "
                f"corpus search would send the question off this machine."
            )
        await self._embedder.embed([query])
        return [
            {
                "url": "corpus://paper.pdf#p3",
                "title": "paper.pdf (p. 3)",
                "content": "Corpus excerpt about recall.",
            }
        ]
