@pytest.mark.asyncio
async def test_everything_scope_combines_every_available_ground(monkeypatch):
    async def fake_search(query: str, max_results: int = 5):
        return [{"url": "https://arxiv.org/abs/2", "title": "Web hit", "content": "Fresh."}]

