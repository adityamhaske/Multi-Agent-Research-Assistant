"""
Decide which build identity this image carries — run by `backend/Dockerfile` after `COPY`.

`research_engine/_build.py` is git-ignored but not Docker-ignored, on purpose: `release.yml`
stamps the build context fresh and `COPY . /app` is how the published images carry that
stamp. The same COPY also carries whatever stamp a developer's checkout happens to hold, and
a leftover one made a local 3.0.2 image report 2.1.0 and a September commit as its identity.

`BUILD_STAMP` says which kind of build this is:

* `context` (the Dockerfile's default, what `release.yml` gets) — keep the context's stamp.
* `local` (what `docker-compose.full.yml` passes) — never trust the context's stamp. Write a
  fresh one only from `BUILD_VERSION`/`BUILD_GIT_SHA`/`BUILD_DIRTY`, which `start.sh` reads
  from git for this build; with any of them missing or malformed, write none, and the image
  answers `unknown` (`research_engine/build_info.py`).

`CONTRACT_VERSION` is left out of a local stamp: hashing the contract means importing the
app, and that logic lives in `scripts/stamp_build.py`, outside this build context. A second
copy could disagree with it; an absent one reads as `unknown`.

Stdlib only, and nothing from `app` — it runs during the image build.
"""

from __future__ import annotations

import os
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

STAMP = Path(__file__).resolve().parent.parent / "research_engine" / "_build.py"

# Validated, not just present: each value is written into a Python module, so anything that
# is not plainly one of these shapes is refused rather than escaped.
_SHAPES = {
    "BUILD_VERSION": re.compile(r"\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?"),
    "BUILD_GIT_SHA": re.compile(r"[0-9a-f]{40}"),
    "BUILD_DIRTY": re.compile(r"true|false"),
}


def main() -> int:
    mode = os.environ.get("BUILD_STAMP", "context")
    if mode == "context":
        return 0
    if mode != "local":
        print(f"BUILD_STAMP={mode!r}: expected 'context' or 'local'", file=sys.stderr)
        return 1

    STAMP.unlink(missing_ok=True)

    facts = {name: os.environ.get(name, "") for name in _SHAPES}
    refused = [name for name, shape in _SHAPES.items() if not shape.fullmatch(facts[name])]
    if refused:
        # Stdout, not an error: an unstamped image is a working image that says `unknown`.
        print(f"build stamp: none ({', '.join(refused)} missing or malformed) — reports unknown")
        return 0

    values = {
        "VERSION": facts["BUILD_VERSION"],
        "GIT_SHA": facts["BUILD_GIT_SHA"],
        "DIRTY": facts["BUILD_DIRTY"] == "true",
        "BUILT_AT": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    lines = ['"""Generated by backend/docker/stamp_image.py for a local image."""', ""]
    lines += [f"{key} = {value!r}" for key, value in values.items()]
    STAMP.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"build stamp: {values['GIT_SHA'][:9]}{' (dirty)' if values['DIRTY'] else ''}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
